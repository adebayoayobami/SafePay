import { createWalletClient, createPublicClient, http, parseAbi, encodeAbiParameters } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import fs from 'fs';
const rpc="https://rpc.test.mezo.org";
const chain={id:31611, name:"Mezo Testnet", nativeCurrency:{name:"BTC",symbol:"BTC",decimals:18}, rpcUrls:{default:{http:[rpc]}}};
const pk="0x"+fs.readFileSync(".env.deploy","utf8").split("=")[1].trim().replace(/^0x/,"");
const account=privateKeyToAccount(pk);
const wallet=createWalletClient({account, chain, transport:http(rpc)});
const pub=createPublicClient({chain, transport:http(rpc)});
const abi=JSON.parse(fs.readFileSync("abi.json","utf8"));
const bytecode="0x"+fs.readFileSync("bytecode.txt","utf8");
const musd="0x118917a40FAF1CD7a13dB0Ef56C86De7973Ac503";
const mezoT="0x7B7c000000000000000000000000000000000001";
const vault="0x0000000000000000000000000000000000000000";
const encoded=encodeAbiParameters([{type:'address'},{type:'address'},{type:'address'}],[musd,mezoT,vault]);
const data=bytecode+encoded.slice(2);
console.log("deploying from",account.address, "balance check...");
const bal=await pub.getBalance({address:account.address});
console.log("BTC balance wei:",bal.toString());
const hash=await wallet.sendTransaction({to:undefined, data, value:0n});
console.log("tx:",hash);
console.log("waiting receipt...");
const r=await pub.waitForTransactionReceipt({hash});
console.log("receipt status:",r.status,"contract:",r.contractAddress,"gas",r.gasUsed.toString());
if(r.contractAddress) fs.writeFileSync("../deployed.txt", r.contractAddress+"\n"+hash);
